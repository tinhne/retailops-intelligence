import path from "node:path";

import { expect, test, type Page } from "@playwright/test";

import { DEMO_STATE, demoStoreId, openTopException } from "./support";

/**
 * Real screenshots of the running product for the README (docs/screenshots). Runs only with
 * E2E_SCREENSHOTS=1 against a freshly seeded stack, signed in as the public demo viewer.
 */
const outDir = path.resolve(__dirname, "../../../../docs/screenshots");

async function capture(page: Page, name: string): Promise<void> {
  await page.waitForLoadState("networkidle");
  await expect(page.locator('[aria-busy="true"]')).toHaveCount(0);
  await page.screenshot({ path: path.join(outDir, `${name}.png`) });
}

test.use({ storageState: DEMO_STATE });

test("README screenshots @screenshots", async ({ page }) => {
  test.setTimeout(180_000);
  const storeId = demoStoreId();
  await page.goto(`/s/${storeId}/overview`);
  await expect(page.getByRole("heading", { level: 1 })).toBeVisible();
  await capture(page, "overview");

  await page.goto(`/s/${storeId}/exceptions`);
  await expect(page.getByRole("link", { name: /^EXC-\d+/ }).first()).toBeVisible();
  await capture(page, "exceptions-inbox");

  await openTopException(page, storeId);
  await expect(page.getByRole("heading", { name: "Evidence" })).toBeVisible();
  await capture(page, "exception-detail");

  await page.goto(`/s/${storeId}/inventory`);
  await expect(page.getByRole("heading", { level: 1 })).toBeVisible();
  await capture(page, "inventory");

  await page.goto(`/s/${storeId}/imports`);
  await expect(page.getByRole("heading", { level: 1 })).toBeVisible();
  await capture(page, "imports");

  await page.goto(`/s/${storeId}/copilot`);
  await page.getByRole("textbox", { name: "Question" }).fill("What needs attention today?");
  await page.getByRole("button", { name: "Send question" }).click();
  await expect(page.getByText(/^Generated by/).first()).toBeVisible({ timeout: 45_000 });
  await capture(page, "copilot");
});
