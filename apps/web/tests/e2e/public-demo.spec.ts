import { expect, test } from "@playwright/test";

import { DEMO_STATE, demoStoreId, exploreDemo, openTopException } from "./support";

/** The public demo (ADR-0011): no registration, real seeded data, and no way to change it. */
test("a visitor explores the demo read-only", async ({ page, context }) => {
  const storeId = await exploreDemo(page);
  await expect(page.getByText("Demo data", { exact: true })).toBeVisible();

  await openTopException(page, storeId);
  await expect(page.getByRole("heading", { name: "Evidence" })).toBeVisible();
  // Lifecycle actions are absent or disabled with a reason for the viewer role.
  const resolve = page.getByRole("button", { name: /Resolve…/ });
  if ((await resolve.count()) > 0) {
    await expect(resolve.first()).toHaveAttribute("aria-disabled", "true");
  }

  // The backend refuses a mutation even when it is sent directly.
  const csrf = (await context.cookies()).find((cookie) => cookie.name === "ro_csrf")?.value ?? "";
  const response = await page.request.post(`/api/v1/stores/${storeId}/evaluations`, {
    headers: { "X-CSRF-Token": csrf, "Content-Type": "application/json" },
    data: {},
  });
  expect(response.status()).toBe(403);
});

test.describe("with the saved demo session", () => {
  test.use({ storageState: DEMO_STATE });

  test("the copilot answers a visitor from the seeded records", async ({ page }) => {
    const storeId = demoStoreId();
    await page.goto(`/s/${storeId}/copilot`);
    await page.getByRole("textbox", { name: "Question" }).fill("Which orders are overdue, and why?");
    await page.getByRole("button", { name: "Send question" }).click();
    await expect(page.getByText(/^Generated by (the deterministic engine|LLM provider)/).first()).toBeVisible({ timeout: 45_000 });
  });
});
