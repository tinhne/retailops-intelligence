    expect(screen.getByText("Data as of Oct 31, 10:00 AM EDT.")).toBeInTheDocument();
    expect(screen.getByText(/Generated by the deterministic engine/)).toBeInTheDocument();

    await userEvent.click(screen.getByRole("button", { name: "Show the formula for Value at risk" }));
    expect(screen.getByText("sum(open line value)")).toBeInTheDocument();
    await userEvent.click(screen.getByRole("button", { name: /Data used: 2 read-only tools/ }));
    expect(screen.getByText(/Exceptions list · 12 rows · 8 ms · OK/)).toBeInTheDocument();
