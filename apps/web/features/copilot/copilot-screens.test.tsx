const replace = vi.fn();
let search = new URLSearchParams();
vi.mock("next/navigation", () => ({
  useRouter: () => ({ replace, push: vi.fn() }),
  usePathname: () => "/s/f0da0f22-b9e0-4483-b144-e9f0f8703d13/copilot",
  useSearchParams: () => search,
  useParams: () => ({ exceptionId: "exc-1" }),
}));

const STORE = "/s/f0da0f22-b9e0-4483-b144-e9f0f8703d13";
const VIEWER: Permission[] = ["dashboard.read", "exceptions.read", "orders.read", "catalog.read", "inventory.read", "imports.read", "copilot.use"];
const MANAGER: Permission[] = [...VIEWER, "exceptions.work", "exceptions.assign", "exceptions.manage", "evaluations.run"];
const CONVERSATION = "7d0c2f4e-1b2a-4c3d-8e9f-0a1b2c3d4e5f";
const page = <T,>(items: T[]) => ({ items, page: 1, page_size: 50, total: items.length });
const conversation = {
  id: CONVERSATION,
  title: "What should I work on first today?",
  context_type: "GENERAL" as const,
  context_id: null,
  message_count: 2,
  created_at: "2026-10-31T14:00:00Z",
  updated_at: "2026-10-31T14:00:01Z",
};

beforeEach(() => {
  replace.mockReset();
  search = new URLSearchParams();
});

