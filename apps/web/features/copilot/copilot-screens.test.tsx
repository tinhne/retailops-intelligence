import { screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { beforeEach, describe, expect, it, vi } from "vitest";

import { ExceptionScreen } from "@/features/exceptions/detail/exception-screen";
import type { Permission } from "@/lib/api/auth";
import { answerFixture, messagesFixture, metaFixture } from "@/test/copilot-fixtures";
import { detailFixture, eventFixture } from "@/test/exception-fixtures";
import { errorResponse, jsonResponse, routeFetch } from "@/test/fetch";
