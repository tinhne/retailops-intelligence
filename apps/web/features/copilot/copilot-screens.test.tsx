    expect(screen.queryByRole("link", { name: "KHK-KT-012" })).not.toBeInTheDocument();
    expect(screen.queryByText("Dashboard summary")).not.toBeInTheDocument();
    expect(screen.getByText("est.")).toBeInTheDocument();
