"""One copilot turn: provider selection, the tool-use loop, validation and fallback (§4, §8).

``run_turn`` captures nothing itself: the caller passes ``as_of`` (one instant for every tool call
of the turn, BR-504) and the store context. The live path prefetches the router or ContextBuilder
plan, then lets the model ask for more tools within the limits, validates the answer (one repair
round-trip when there is headroom) and raises ``ProviderFailure`` on anything it cannot accept.
Every failure falls back to the deterministic provider for this answer, with the reason and a
visible notice; tool results already fetched are reused, so both paths describe the same instant.
"""

